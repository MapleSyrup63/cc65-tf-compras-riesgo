// ClasificarRubro asigna un rubro de gasto a partir de la descripción normalizada.
func ClasificarRubro(desc string) string {
	d := " " + noAccents(desc)
	for i, kws := range rubroKeywords {
		for _, k := range kws {
			if strings.Contains(d, k) {
				return Rubros[i]
			}
		}
	}
	return "OTROS"
}
